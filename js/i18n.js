  const LS_KEY = "despega_lang";
  let lang = localStorage.getItem(LS_KEY) || "es";
  if (!DICT[lang]) lang = "es";
  const listeners = [];

  function t(key, vars) {
    let s = (DICT[lang] && DICT[lang][key]) || DICT.es[key] || key;
    if (vars) for (const k in vars) s = s.split("{" + k + "}").join(vars[k]);
    return s;
  }

  function apply(root) {
    const scope = root || document;
    scope.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.dataset.i18n); });
    scope.querySelectorAll("[data-i18n-html]").forEach((el) => { el.innerHTML = t(el.dataset.i18nHtml); });
    scope.querySelectorAll("[data-i18n-ph]").forEach((el) => { el.placeholder = t(el.dataset.i18nPh); });
  }

  function setLang(l) {
    if (!DICT[l]) return;
    lang = l;
    localStorage.setItem(LS_KEY, l);
    document.documentElement.lang = l;
    apply();
    listeners.forEach((fn) => fn(l));
  }

  function onChange(fn) { listeners.push(fn); }

  return { t, apply, setLang, onChange, get lang() { return lang; } };
